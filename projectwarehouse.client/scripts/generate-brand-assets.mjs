// Converts src/assets/logo.svg (a white silhouette) into:
//   - public/favicon.svg           (transparent, logo tinted with the accent color)
//   - public/favicon.ico           (16/32/48px multi-res, same composition — fallback for browsers without SVG favicon support)
//   - public/icon-512x512.png      (logo on a brand-color background square with maskable safe-zone padding, for the PWA manifest)
//   - public/icon-192x192.png      (same composition, for the PWA manifest)
//   - public/apple-touch-icon.png  (180x180, same composition — iOS ignores manifest.icons)
//   - src/components/icons/LogoIcon.tsx (MUI createSvgIcon component, fill left as currentColor)
// Usage: node scripts/generate-brand-assets.mjs
import {mkdir, readFile, writeFile} from "node:fs/promises";
import {fileURLToPath} from "node:url";
import path from "node:path";
import sharp from "sharp";
import pngToIco from "png-to-ico";

const BACKGROUND_COLOR = "#1976d2";
// Keep in sync with palette.primary.main in src/theme.ts.
const ACCENT_COLOR = "#90caf9";
// Fraction of the canvas the logo occupies, centered — the rest is safe-zone padding so Android's
// adaptive-icon mask (a circle/squircle crop) never clips the mark.
const PWA_SAFE_ZONE_SCALE = 0.6;

const clientRoot = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const sourcePath = path.join(clientRoot, "src/assets/logo.svg");
const faviconPath = path.join(clientRoot, "public/favicon.svg");
const faviconIcoPath = path.join(clientRoot, "public/favicon.ico");
const FAVICON_ICO_SIZES = [16, 32, 48];
const iconComponentPath = path.join(clientRoot, "src/components/icons/LogoIcon.tsx");

const pwaIconTargets = [
  {path: path.join(clientRoot, "public/icon-512x512.png"), size: 512},
  {path: path.join(clientRoot, "public/icon-192x192.png"), size: 192},
  {path: path.join(clientRoot, "public/apple-touch-icon.png"), size: 180},
];

const source = await readFile(sourcePath, "utf8");

const viewBoxMatch = source.match(/viewBox="([^"]+)"/);
if (!viewBoxMatch) {
  throw new Error(`Could not find viewBox in ${sourcePath}`);
}
const viewBox = viewBoxMatch[1];
const [, , width, height] = viewBox.split(/\s+/);

const shapeElements = [...source.matchAll(/<(path|polygon)\b[^>]*\/>/g)]
  .map((m) => m[0])
  .map((el) => el.replace(/\s*class="fil0"/, ""));

if (shapeElements.length === 0) {
  throw new Error(`Could not find any path/polygon elements in ${sourcePath}`);
}

const faviconSvg = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="${viewBox}">
  <g fill="${ACCENT_COLOR}" fill-rule="evenodd" clip-rule="evenodd">
    ${shapeElements.join("\n    ")}
  </g>
</svg>
`;

await writeFile(faviconPath, faviconSvg, "utf8");

const faviconPngBuffers = await Promise.all(
  FAVICON_ICO_SIZES.map((size) =>
    sharp(Buffer.from(faviconSvg)).resize(size, size).png().toBuffer(),
  ),
);
await writeFile(faviconIcoPath, await pngToIco(faviconPngBuffers));

const pwaOffset = ((1 - PWA_SAFE_ZONE_SCALE) / 2) * Number(width);
const pwaSvg = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="${viewBox}">
  <rect width="${width}" height="${height}" fill="${BACKGROUND_COLOR}"/>
  <g transform="translate(${pwaOffset} ${pwaOffset}) scale(${PWA_SAFE_ZONE_SCALE})">
    <g fill="#fff" fill-rule="evenodd" clip-rule="evenodd">
      ${shapeElements.join("\n      ")}
    </g>
  </g>
</svg>
`;

for (const {path: targetPath, size} of pwaIconTargets) {
  await sharp(Buffer.from(pwaSvg)).resize(size, size).png().toFile(targetPath);
}

const iconJsx = shapeElements
  .map((el) => el.replace(/\bpoints="/, 'points="').replace(/\/>$/, " />"))
  .join("\n    ");

const iconComponent = `import {createSvgIcon, type SvgIconProps} from "@mui/material";

// Generated by scripts/generate-brand-assets.mjs from src/assets/logo.svg — do not hand-edit the markup.
const LogoIconBase = createSvgIcon(
  <g fillRule="evenodd" clipRule="evenodd">
    ${iconJsx}
  </g>,
  "Logo",
);

export const LogoIcon = (props: SvgIconProps) => (
  <LogoIconBase viewBox="${viewBox}" {...props} />
);
`;

await mkdir(path.dirname(iconComponentPath), {recursive: true});
await writeFile(iconComponentPath, iconComponent, "utf8");

console.log(`Wrote ${path.relative(clientRoot, faviconPath)}`);
console.log(`Wrote ${path.relative(clientRoot, faviconIcoPath)}`);
for (const {path: targetPath} of pwaIconTargets) {
  console.log(`Wrote ${path.relative(clientRoot, targetPath)}`);
}
console.log(`Wrote ${path.relative(clientRoot, iconComponentPath)}`);
